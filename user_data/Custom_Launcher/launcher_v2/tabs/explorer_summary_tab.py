        self.loop_var = tk.StringVar(value="-")
        self.target_var = tk.StringVar(value="-")
        self.breadth_var = tk.StringVar(value="-")
        self.training_var = tk.StringVar(value="-")
        self.validation_count_var = tk.StringVar(value="-")
        self.decision_var = tk.StringVar(value="-")
        self.changed_var = tk.StringVar(value="-")

        ttk.Label(header, text="Active strategy").grid(row=0, column=0, sticky="w", padx=8, pady=4)
        ttk.Label(header, textvariable=self.strategy_var).grid(row=0, column=1, columnspan=7, sticky="ew", padx=8, pady=4)

        fields = [
            ("Loop", self.loop_var),
            ("Target", self.target_var),
            ("Breadth", self.breadth_var),
            ("Training", self.training_var),
            ("Validation windows", self.validation_count_var),
            ("Decision", self.decision_var),
            ("Changed params", self.changed_var),
        ]
        for idx, (label, variable) in enumerate(fields):
            row = 1 + (idx // 4)
            col = (idx % 4) * 2
            ttk.Label(header, text=label).grid(row=row, column=col, sticky="w", padx=8, pady=4)
            ttk.Label(header, textvariable=variable).grid(row=row, column=col + 1, sticky="ew", padx=8, pady=4)

        loops_frame = ttk.LabelFrame(self, text="Run Loop History")
        loops_frame.grid(row=1, column=0, sticky="nsew", padx=8, pady=(0, 8))
        loops_frame.grid_columnconfigure(0, weight=1)
        loops_frame.grid_rowconfigure(0, weight=1)
