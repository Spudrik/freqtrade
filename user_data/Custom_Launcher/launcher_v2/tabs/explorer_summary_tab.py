FAIL_DECISIONS = {"REJECTED_BACKTEST_FAILED", "REJECTED_NO_TUNABLE_PARAMS"}


class ExplorerSummaryTab(BaseTab):
    """Explorer summary and loop review.

    Reads compact summary + audit metadata generated by the Explorer runner.
    This UI is read-only and strategy-scoped by active Setup strategy.
    """

    tab_key = "explorer_summary"
    tab_title = "Explorer Summary"

    def __init__(self, master: tk.Misc, context: Any) -> None:
        super().__init__(master, context)
        self.summary_path = context.app_dir.parent / "explorer_reports" / "latest_summary.json"
        self.audit_dir = context.app_dir.parent / "explorer_reports" / "runs"
        self.presets_path = context.app_dir / "launcher_v2" / "config" / "presets.json"
        self._refresh_after_id: str | None = None
        self._loop_row_map: dict[str, dict[str, Any]] = {}
        self._build_ui()
        self.refresh()

